"""生成 quotes-chapters-batch24.js,确保每条语录独特不重复"""


def build_chapter(ch_id, group, icon, title, quotes):
    lines = []
    lines.append(f"## {title}\n")
    for i, (stmt, reply) in enumerate(quotes):
        lines.append(f'> "{stmt}"')
        lines.append(f'> **回:** {reply}')
        if i < len(quotes) - 1:
            lines.append("")
            lines.append("---")
            lines.append("")
    content = "\n".join(lines)
    return f"""  // ============================================================
  // {title}
  // ============================================================
  {{
    id: '{ch_id}',
    group: '{group}',
    icon: '{icon}',
    title: '{title}',
    content: `{content}`,
  }},"""


def dedupe(qs):
    seen = set()
    out = []
    for s, r in qs:
        if (s, r) not in seen:
            seen.add((s, r))
            out.append((s, r))
    return out



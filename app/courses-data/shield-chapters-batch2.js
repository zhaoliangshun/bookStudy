七大法则是回怼的总纲。话术千变万化，但万变不离其宗：

1. **不辩解**——不向对方证明自己
2. **不被带跑**——守住自己的话题
3. **不情绪化**——冷静就是力量
4. **让对方举证**——谁主张谁举证
5. **就事论事**——不升级到人身
6. **留有余地**——给对方台阶
7. **知道何时停止**——目的达到就停


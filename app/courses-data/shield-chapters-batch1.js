- "哎呀开玩笑的，你怎么这么开不起玩笑？"
- "你不会连这个都介意吧？我以前的朋友都没事。"
- "帮个小忙嘛，至于这么小气吗？"
- "你别这么认真嘛，大家图个乐。"

**应对核心**：第一次试探就要明确反击。破窗效应的关键是第一扇窗——只要第一扇不被打破，后面就安稳。


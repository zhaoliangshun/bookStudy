很多人之所以害怕，是因为把暴怒的对方想象得太可怕了——觉得他像个怪兽一样，能把自己吞了。但你仔细想想：他也就是个普通人，他发脾气是因为他自己控制不了自己的情绪，是他自己有问题，不是因为你有多糟糕，也不是因为他有多强大。


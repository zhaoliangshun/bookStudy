- 他们知道情绪是暂时的，来了会走，不会抓住不放
- 他们不会因为别人的错误惩罚自己
- 他们即使在脆弱的时候，也心里清楚：我会好起来的，这一切都会过去的

他们是有弹性的人——不是不会被打倒，是被打倒了能自己站起来，拍拍身上的灰，继续往前走。就像一棵大树，风来了它会晃，雨来了它会被淋湿，但风雨过后，它还是稳稳地站在那里，根越扎越深。


"然后我还在继续说，说新工作工资更高什么的。然后他就突然把遥控器摔了……"

你看，信号早就有了——坐直身体、攥拳头、不说话、盯着看、下巴绷紧、深呼吸——这些都是暴怒来临前的明确信号。但小周完全没有意识到这些信号意味着什么，她还在继续说，直到对方彻底爆炸。


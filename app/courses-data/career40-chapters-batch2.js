// 一个 Cloudflare Worker，处理 TODO 的 CRUD
export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    const path = url.pathname;

    // 路由：GET /todos 获取列表
    if (path === "/todos" && request.method === "GET") {
      const { results } = await env.DB.prepare("SELECT * FROM todos").all();
      return Response.json(results);
    }

    // 路由：POST /todos 新增
    if (path === "/todos" && request.method === "POST") {
      const { title } = await request.json();
      await env.DB.prepare("INSERT INTO todos (title) VALUES (?)")
        .bind(title)
        .run();
      return Response.json({ ok: true });
    }

    return new Response("Not Found", { status: 404 });
  },
};

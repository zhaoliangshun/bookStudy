"化疗完了那天，我从医院出来，阳光照在脸上，风吹过来，我突然觉得——活着真好。不是嘴上说说的那种'活着真好'，是从脚底一直到头顶的、每一个细胞都觉得'能感觉到风、能感觉到阳光，真好'。我活了五十一年，从来没有哪一刻，这么强烈地觉得活着好。"


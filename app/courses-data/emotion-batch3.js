不是说不能有目标。人活着总得往前走，总得有点想做的事。但问题是，**很多人把幸福绑在了结果上**。结果好就开心，结果不好就崩溃。你的快乐完全交给了一个你控制不了的东西——而结果，恰恰是你最控制不了的。


秋深了。院子里的银杏开始落叶子，一片一片，慢悠悠地，从枝头飘到地上。

没有一片叶子是慌张的。它们不在枝头死撑，也不急着往下跳。风来了，它们就跟着风走；风停了，它们就落到该落的地方。有的落在台阶上，有的落在水池里，有的被孩子捡了去夹在书里，有的被扫帚拢到墙角。


人的苦，大半来自强求。

强求一个人不变心。强求一件事必成。强求一份付出必有回报。强求生活按照自己的剧本走。

可缘是不讲道理的。它不会因为你想怎样就怎样。你想留住一个人，可条件变了，缘分尽了，你留不住；你想做成一件事，可时机未到，条件未齐，你做不成。强求，就是把人力硬塞进缘的缝隙里，想撬出一个自己想要的结果。

结果往往是：你撬得越用力，伤得越深。


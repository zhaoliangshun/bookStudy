落到生活里，怎么找这个平衡？

**第一，分清什么是必须担的，什么是可以放的。**

赡养父母、抚育孩子、忠于职守、信于朋友——这些是必须担的，担起来不叫累，叫本分。攀比、虚荣、他人的眼光、不必要的应酬——这些是可以放的，放下了不叫失，叫解脱。


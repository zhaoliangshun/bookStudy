紧张不只是呼吸的事，还有肌肉的事。回想一下你紧张时的身体：肩膀是不是耸起来了？下巴是不是咬紧了？眉头是不是皱起来了？手是不是握成了拳？这些不自觉的肌肉紧张，会反过来加重你的紧张感。


- 展示你的思考过程，让面试官了解你的问题解决能力
- 即使最终答案不完美，良好的思考过程也能为你赢得分数
- 给面试官提供介入和引导的机会，避免走太多弯路
- 展示你的沟通能力——这是团队协作的基础


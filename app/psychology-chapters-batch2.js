创伤后的人，容忍之窗往往变得很窄——一点小事就把他推到高唤起（暴怒、惊恐）或低唤起（解离、麻木）。疗愈的核心目标之一，就是**扩大容忍之窗**——让神经系统在更大的刺激范围内仍能保持调节。这通过反复的、安全的、渐进的体验来实现，让神经系统「学习」可以承受更多而不崩溃。


「反移情」（countertransference）是咨询师对来访者的情感反应，它同样有价值——咨询师感受到的强烈情绪，往往是来访者「不能感受」或「投射出来」的。训练有素的咨询师会把反移情当作理解来访者的工具。这就是为什么精神动力学治疗特别强调「关系本身就是疗愈」——不是技术的应用，而是这段真实、安全、可反思的关系，重新塑造了来访者的内在客体世界。

